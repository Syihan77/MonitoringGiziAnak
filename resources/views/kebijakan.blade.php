<p class="selamat-datang-di">
Selamat datang di Sistem Monitoring dan Rekomendasi Gizi Anak. Dokumen ini mengatur ketentuan penggunaan layanan serta perlindungan data bagi seluruh pengguna, baik Orang Tua/Wali maupun Kader Posyandu.<br><br>
Dengan mendaftar dan menggunakan sistem ini, Anda menyetujui poin-poin berikut:<br><br>
Pengumpulan dan Penggunaan Data<br>
Sistem mengumpulkan informasi seperti identitas, data pertumbuhan (berat dan tinggi badan), serta catatan konsumsi harian anak. Data ini digunakan secara eksklusif untuk:<br>
Memberikan analisis kecukupan gizi harian dan rekomendasi menu sehat yang sesuai dengan ketersediaan bahan di rumah dan anggaran keluarga bagi Orang Tua.<br>
Menyediakan rekam jejak konsumsi dan pertumbuhan anak yang dapat dipantau oleh Kader Posyandu untuk mendukung evaluasi kesehatan bulanan tanpa mengubah data riwayat konsumsi pribadi.<br><br>
Batasan Layanan (Penyangkalan Medis)<br>
Sistem ini merupakan alat bantu edukatif (Sistem Pendukung Keputusan) untuk upaya deteksi dini dan pencegahan stunting di tingkat keluarga. Segala hasil analisis gizi dan rekomendasi menu yang diberikan BUKAN merupakan diagnosis klinis medis. Penentuan status kesehatan dan stunting tetap menjadi wewenang penuh tenaga kesehatan dan kader Posyandu melalui pengukuran antropometri langsung.<br><br>
Kewajiban Pengguna<br>
Bagi Orang Tua: Bertanggung jawab memasukkan data anak dan asupan makanan harian secara akurat agar sistem dapat memberikan rekomendasi menu yang optimal.<br>
Bagi Kader Posyandu: Memiliki kewajiban etika untuk menjaga kerahasiaan seluruh data rekam riwayat asupan dan pertumbuhan warga. Kader dilarang keras menyebarluaskan, membagikan, atau menyalahgunakan informasi pribadi anak dari sistem ini kepada pihak yang tidak berwenang.<br><br>
Keamanan dan Kerahasiaan<br>
Kami berkomitmen melindungi privasi anak dan keluarga Anda. Data kesehatan dan identitas yang tersimpan tidak akan dipublikasikan ke ruang publik, tidak diperjualbelikan, dan tidak akan dibagikan kepada pihak ketiga di luar kepentingan evaluasi program pencegahan stunting dan pelayanan kesehatan instansi mitra kami.<br><br>
Pembaruan Sistem<br>
Kami berhak mengubah ketentuan ini sewaktu-waktu untuk peningkatan layanan. Penggunaan yang berkelanjutan atas sistem ini dianggap sebagai persetujuan terhadap perubahan tersebut.
